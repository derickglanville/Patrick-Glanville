const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('C:/Users/deric/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const pin = source.match(/const ADMIN_CLIENT_ACCESS_PIN = "([^"]+)"/)?.[1];
if (!pin) throw new Error('Admin access code not found');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    await page.route(/^https?:\/\//, route => route.abort()); // Browser test must never write to live Firebase.
    await page.route('https://data.ny.gov/resource/rc94-5y2u.json*', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[{"date":"2026-10-05T00:00:00.000","lower_hudson_average_gal":"6.25"}]' }));
    await page.route(url => url.hostname === 'data.ny.gov' && url.searchParams.get('$limit') === '5000', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[{"date":"2026-10-05T00:00:00.000","lower_hudson_average_gal":"6.25"},{"date":"2026-09-28T00:00:00.000","lower_hudson_average_gal":"6.15"},{"date":"2026-09-21T00:00:00.000","lower_hudson_average_gal":"6.30"},{"date":"2026-08-01T00:00:00.000","lower_hudson_average_gal":"5.50"},{"date":"2025-09-01T00:00:00.000","lower_hudson_average_gal":"3.80"}]' }));
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href, { waitUntil: 'domcontentloaded' });
    await page.locator('#topClientSelect').selectOption('admin');
    await page.locator('#topClientPin').fill(pin);
    await page.waitForTimeout(800);
    assert.equal(await page.locator('#homeHeatingOilBtn').isVisible(), true);
    await page.locator('#homeHeatingOilBtn').click();
    assert.match(await page.locator('#homeHeatingOilBody').innerText(), /270 gal/);
    assert.match(await page.locator('#homeHeatingOilBody').innerText(), /1[23][0-9] gal/);
    assert.equal(await page.locator('#oilUsageYear').inputValue(), '2025');
    await page.locator('#oilPrevYear').click();
    assert.equal(await page.locator('#oilUsageYear').inputValue(), '2024');
    const year2024 = await page.locator('.oil-chart-bars').innerText();
    await page.locator('#oilUsageYear').selectOption('2015');
    assert.notEqual(await page.locator('.oil-chart-bars').innerText(), year2024);
    await page.locator('#oilUsageYear').selectOption('2026');
    assert.match(await page.locator('.oil-chart-bars').innerText(), /—/);
    await page.locator('#oilUsageYear').selectOption('average');
    assert.match(await page.locator('.oil-card').first().innerText(), /2022–present delivery intervals/);
    assert.match(await page.locator('.oil-annual-bars').innerText(), /2015/);
    await page.locator('[data-oil-tab="prices"]').click();
    await page.getByText('$6.25 / gal').waitFor();
    assert.match(await page.locator('.oil-price-view').innerText(), /Survey 2026-10-05/);
    assert.match(await page.locator('.oil-price-view').innerText(), /\$5\.72 \/ gal/);
    assert.match(await page.locator('.oil-price-costs').innerText(), /\$937\.50/);
    assert.equal(await page.locator('.oil-price-metric a').count(), 2);
    await page.locator('[data-oil-tab="priceHistory"]').click();
    await page.getByText('+$0.10 / gal').waitFor();
    assert.equal(await page.locator('.oil-history-table tbody tr').count(), 3);
    assert.match(await page.locator('.oil-history-table tbody').innerText(), /2026-10-05/);
    assert.equal(await page.locator('.oil-history-chart path').count(), 1);
    assert.equal(await page.locator('.oil-history-grid line').count(), 10);
    await page.locator('#oilHistorySvg').click({ position: { x: 5, y: 120 } });
    assert.match(await page.locator('#oilHistoryPointInfo').innerText(), /2026-09-21 · \$6\.30 per gallon/);
    assert.equal(await page.locator('#oilHistoryCrosshairX').getAttribute('visibility'), 'visible');
    await page.locator('#oilHistorySvg').press('ArrowRight');
    assert.match(await page.locator('#oilHistoryPointInfo').innerText(), /2026-09-28 · \$6\.15 per gallon/);
    await page.locator('[data-oil-range="week"]').click();
    assert.equal(await page.locator('.oil-history-table tbody tr').count(), 2);
    await page.locator('[data-oil-range="year"]').click();
    assert.equal(await page.locator('.oil-history-table tbody tr').count(), 4);
    await page.locator('[data-oil-range="all"]').click();
    assert.equal(await page.locator('.oil-history-table tbody tr').count(), 5);
    await page.locator('[data-oil-range="month"]').click();
    assert.equal(await page.locator('.oil-history-table tbody tr').count(), 3);
    await page.locator('[data-oil-tab="overview"]').click();
    if (process.env.OIL_SCREENSHOT) await page.locator('#homeHeatingOilDialog').screenshot({ path: process.env.OIL_SCREENSHOT });
    await page.locator('[data-oil-tab="deliveries"]').click();
    assert.equal(await page.locator('.oil-table tbody tr').count(), 60);
    await page.locator('#oilAddDelivery').click();
    await page.locator('#oilDeliveryForm [name="date"]').fill('2026-10-14');
    await page.locator('#oilDeliveryForm [name="gallons"]').fill('100');
    await page.locator('#oilDeliveryForm [name="price"]').fill('3.25');
    await page.locator('#oilDeliveryForm [name="company"]').fill('Test Fuel');
    await page.locator('#oilDeliveryForm button[type="submit"]').click();
    assert.equal(await page.locator('.oil-table tbody tr').count(), 61);
    await page.locator('[data-oil-tab="readings"]').click();
    assert.match(await page.locator('.oil-table tbody').innerText(), /2026-10-14 09:30/);
    await page.locator('.oil-edit-reading').first().click();
    await page.locator('#oilReadingForm [name="percent"]').selectOption('25');
    await page.locator('#oilReadingForm button[type="submit"]').click();
    await page.locator('[data-oil-tab="overview"]').click();
    assert.match(await page.locator('#homeHeatingOilBody').innerText(), /25% around/);
    assert.deepEqual(errors, []);
    process.stdout.write('PASS: Admin oil tracker imports 60 deliveries, adds a delivery, saves a reading, and renders an outlook.\n');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
